/**
 * Prepares the files the phone-resident app needs:
 *   - vendors SQLite compiled to WebAssembly into public/vendor
 *   - turns the .sql migrations into a JS module, so the app carries its own
 *     schema and needs no server to fetch it from
 *
 * Run after changing a migration:  npm run build:local
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readMigrations } from '../server/db-node.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = path.join(ROOT, 'public', 'vendor');
const LOCAL = path.join(ROOT, 'public', 'js', 'local');

fs.mkdirSync(VENDOR, { recursive: true });
fs.mkdirSync(LOCAL, { recursive: true });

// ---- SQLite WASM ----------------------------------------------------------
// The built copies are committed, so a fresh checkout needs no npm install and
// the app keeps its promise of having no dependencies to fetch.
const candidates = [
  path.join(ROOT, 'node_modules', '@sqlite.org', 'sqlite-wasm', 'dist'),
];
const source = candidates.find((dir) => fs.existsSync(path.join(dir, 'sqlite3.wasm')));
const alreadyVendored = fs.existsSync(path.join(VENDOR, 'sqlite3.wasm'));

if (source) {
  fs.copyFileSync(path.join(source, 'index.mjs'), path.join(VENDOR, 'sqlite3.mjs'));
  fs.copyFileSync(path.join(source, 'sqlite3.wasm'), path.join(VENDOR, 'sqlite3.wasm'));
  const size = (fs.statSync(path.join(VENDOR, 'sqlite3.wasm')).size / 1024).toFixed(0);
  console.log(`[local] vendored SQLite WASM from node_modules (${size} KB)`);
} else if (alreadyVendored) {
  console.log('[local] using the SQLite WASM already in public/vendor');
} else {
  console.error('SQLite WASM missing. Run:  npm install @sqlite.org/sqlite-wasm');
  process.exit(1);
}

// ---- the portable half of the server, copied where a browser can load it ---
// The phone runs the very same route files; these are copies, not a rewrite,
// and this script is what keeps them identical.
const SHARED = path.join(ROOT, 'public', 'shared');
const PORTABLE = [
  'db.js',
  'lib/http.js', 'lib/errors.js', 'lib/auth.js', 'lib/crypto.js', 'lib/runtime.js',
  'lib/validate.js', 'lib/money.js', 'lib/messaging.js', 'lib/audit.js',
  'lib/sync-schema.js', 'lib/sync-core.js', 'lib/sync-client.js',
  'lib/licence.js', 'lib/licence-state.js',
  'routes/auth.js', 'routes/users.js', 'routes/settings.js', 'routes/patients.js',
  'routes/appointments.js', 'routes/procedures.js', 'routes/clinical.js',
  'routes/invoices.js', 'routes/payments.js', 'routes/expenses.js',
  'routes/reports.js', 'routes/messages.js', 'routes/licence.js',
  'routes/attachments.js', 'routes/stock.js', 'routes/medicines.js',
  'lib/dental-formulary.js', 'lib/assistant.js', 'routes/assistant.js',
];

fs.rmSync(SHARED, { recursive: true, force: true });
for (const rel of PORTABLE) {
  const from = path.join(ROOT, 'server', rel);
  const to = path.join(SHARED, rel);
  const body = fs.readFileSync(from, 'utf8');
  if (/from '(node|fs|path|os):/.test(body) || /from 'node:/.test(body)) {
    console.error(`[local] ${rel} imports a Node module and cannot run in a phone`);
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.writeFileSync(to, body);
}
fs.writeFileSync(path.join(SHARED, 'README.md'),
  '# Generated\n\nCopies of the portable half of `server/`, placed here so the\n'
  + 'phone app can import the very same route code. Do not edit: run\n'
  + '`npm run build:local` after changing anything under `server/`.\n');
console.log(`[local] copied ${PORTABLE.length} shared modules into public/shared`);

// ---- migrations as a module ----------------------------------------------
const migrations = readMigrations();
const module = `/**
 * The database schema, embedded so the app carries it wherever it runs.
 * Generated by scripts/build-local.js — do not edit; change the .sql files.
 */
export const MIGRATIONS = ${JSON.stringify(migrations, null, 2)};
`;
fs.writeFileSync(path.join(LOCAL, 'migrations.js'), module);
console.log(`[local] embedded ${migrations.length} migrations `
  + `(${migrations.map((m) => m.name).join(', ')})`);

// ---- the seller's public key ----------------------------------------------
// The phone has to be able to check a licence with no server in reach, so the
// key travels with it. It is public: it can verify a code, never mint one.
const KEY_FILE = path.join(ROOT, 'server', 'licence-public.txt');
const licenceKey = fs.existsSync(KEY_FILE) ? fs.readFileSync(KEY_FILE, 'utf8').trim() : '';
fs.writeFileSync(path.join(LOCAL, 'licence-key.js'),
  '/** Generated by scripts/build-local.js \u2014 do not edit. */\n'
  + `export const LICENCE_PUBLIC_KEY = '${licenceKey}';\n`);
console.log(licenceKey
  ? '[local] embedded the licence public key'
  : '[local] no licence public key \u2014 this build enforces nothing');

// ---- which build this is --------------------------------------------------
// Replacing the files and still seeing the old screens is the commonest way an
// update goes wrong — usually because the copy being served is somewhere else.
// Printing the version where staff can see it turns that into a glance.
const { version } = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
fs.writeFileSync(path.join(ROOT, 'public', 'js', 'version.js'),
  `/** Generated by scripts/build-local.js — do not edit. */\nexport const VERSION = '${version}';\n`);
console.log(`[local] stamped version ${version}`);
